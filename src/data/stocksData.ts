// Whether the terminal can draw an option chain around this symbol. Lot size is
// a separate question — stock options have none listed (see lotSizeFor) — so it
// cannot stand in for this one without routing all the stock underlyings to the
// equity chart.
export const hasFnoContracts = (symbol: string): boolean => {
  const s = symbol.toUpperCase();
  return FNO_INDEX_UNDERLYINGS.includes(s) || FNO_STOCK_UNDERLYINGS.has(s);
};

