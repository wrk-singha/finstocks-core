const INDEX_SYMBOL_SET = new Set(NSE_INDICES.map(i => i.symbol));

// A symbol counts as an index (not a real equity) if it is a listed index, an
// F&O underlying, a NIFTY-prefixed benchmark, India VIX, or the screener's
// synthetic CUSTOM_LIST universe.
// drift resolved 2026-09-13: the mobile checked only F&O underlyings, the NIFTY
// prefix and INDIAVIX; the web's superset (index list, constituent keys,
// CUSTOM_LIST) wins because the screener universe picker sends CUSTOM_LIST.
export const isIndexSymbol = (symbol: string): boolean => {
  const s = symbol.toUpperCase();
  return (
    INDEX_CONSTITUENT_KEYS.has(s) ||
    INDEX_SYMBOL_SET.has(s) ||
    s.startsWith('NIFTY') ||
    FNO_INDEX_UNDERLYINGS.includes(s) ||
    s === 'CUSTOM_LIST' ||
    s === 'INDIAVIX'
  );
};

// Spread order: the equity name wins a collision with the index list. INDIAVIX
// is the only symbol in both, and it must keep resolving to "India VIX", not
// the index list's "INDIA VIX".
// drift resolved 2026-09-13: the mobile map had no commodity names; the web's
// does, and the MCX contracts render through the same displayName.
const NAME_BY_SYMBOL: Readonly<Record<string, string>> = {
  ...Object.fromEntries(NSE_INDICES.map(s => [s.symbol, s.name])),
  ...NIFTY100_NAME_OVERRIDES,
  ...Object.fromEntries(COMMODITIES.map(c => [c.symbol, c.name])),
};

export const displayName = (symbol: string): string =>
  NAME_BY_SYMBOL[symbol] ?? symbol;
