// Generates the consumable token outputs from tokens/src/*.json.
//   src/tokens/index.ts        typed, frozen objects (consumers: @finstocks/core/tokens)
//   tokens/dist/tokens.css     CSS custom properties (consumers: @finstocks/core/tokens.css)
// `--check` regenerates in memory and fails if the committed outputs differ.
import {readFileSync, writeFileSync, mkdirSync, existsSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';

// Outputs are formatted with the repo's Prettier config so they are byte-stable whether the
// generator or a lint-staged pass touched them last; `--check` then compares like with like.
const prettier = createRequire(import.meta.url)('prettier');

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..');
const src = name =>
  JSON.parse(readFileSync(join(here, '..', 'src', name), 'utf8'));
const color = src('color.json'),
  type = src('type.json'),
  space = src('space.json'),
  motion = src('motion.json');

const isPair = v =>
  Array.isArray(v) && v.length === 2 && v.every(x => typeof x === 'string');
const leaf = v =>
  isPair(v)
    ? {value: v, description: undefined}
    : v && typeof v === 'object' && isPair(v.value)
      ? v
      : null;
const stripMeta = obj =>
  Object.fromEntries(Object.entries(obj).filter(([k]) => !k.startsWith('$')));

function tsObject(node, indent, docs) {
  const pad = ' '.repeat(indent);
  const lines = ['{'];
  for (const [k, v] of Object.entries(stripMeta(node))) {
    const l = leaf(v);
    const key = /^[a-zA-Z_$][\w$]*$/.test(k) ? k : JSON.stringify(k);
    const desc =
      l?.description ?? (v && typeof v === 'object' && v.$description);
    if (desc) lines.push(`${pad}  /** ${desc.replace(/\*\//g, '* /')} */`);
    if (l)
      lines.push(
        `${pad}  ${key}: ${JSON.stringify(docs === 'light' ? l.value[0] : l.value[1])},`,
      );
    else if (v && typeof v === 'object')
      lines.push(`${pad}  ${key}: ${tsObject(v, indent + 2, docs)},`);
    else lines.push(`${pad}  ${key}: ${JSON.stringify(v)},`);
  }
  lines.push(`${pad}}`);
  return lines.join('\n');
}
const plain = (obj, indent = 0) => {
  const pad = ' '.repeat(indent);
  if (obj === null || typeof obj !== 'object' || Array.isArray(obj))
    return JSON.stringify(obj);
  const lines = ['{'];
  for (const [k, v] of Object.entries(obj)) {
    if (k.startsWith('$')) continue;
    const key = /^[a-zA-Z_$][\w$]*$/.test(k) ? k : JSON.stringify(k);
    if (v && typeof v === 'object' && v.$description)
      lines.push(`${pad}  /** ${v.$description} */`);
    lines.push(`${pad}  ${key}: ${plain(v, indent + 2)},`);
  }
  lines.push(`${pad}}`);
  return lines.join('\n');
};

const header = `// GENERATED by tokens/scripts/build.mjs from tokens/src/*.json — do not edit.\n// Source of truth for every colour, type role, space step, radius, elevation, motion timing and\n// z-index on web and mobile. Change the JSON, run \`pnpm tokens:build\`, commit both.\n\n`;
const ts =
  header +
  `export const colorLight = ${tsObject(color, 0, 'light')} as const;\n\n` +
  `export const colorDark = ${tsObject(color, 0, 'dark')} as const;\n\n` +
  `export type ColorScheme = 'light' | 'dark';\nexport type ColorTokens = typeof colorLight;\nexport const color = {light: colorLight, dark: colorDark} as const;\n\n` +
  `export const type = ${plain(type)} as const;\n\n` +
  `export const space = ${plain(space.space)} as const;\nexport const radius = ${plain(space.radius)} as const;\nexport const layout = ${plain(space.layout)} as const;\n` +
  `export const zIndex = ${plain(space.zIndex)} as const;\nexport const elevation = ${plain(space.elevation)} as const;\n\n` +
  `export const motion = ${plain(motion)} as const;\n\n` +
  `export type TypeRole = keyof typeof type.role;\nexport type SpaceStep = keyof typeof space;\nexport type RadiusStep = keyof typeof radius;\n`;

// ---- CSS custom properties ----
function cssVars(node, idx, prefix, out) {
  for (const [k, v] of Object.entries(stripMeta(node))) {
    const l = leaf(v);
    if (l) out.push(`  --color-${prefix}${k}: ${l.value[idx]};`);
    else cssVars(v, idx, `${prefix}${k}-`, out);
  }
  return out;
}
const kebab = s => s.replace(/[A-Z]/g, m => '-' + m.toLowerCase());
const flat = (obj, prefix, out = []) => {
  for (const [k, v] of Object.entries(stripMeta(obj))) {
    if (v && typeof v === 'object' && !Array.isArray(v))
      flat(v, `${prefix}${kebab(k)}-`, out);
    else
      out.push(
        `  --${prefix}${kebab(k)}: ${Array.isArray(v) ? `cubic-bezier(${v.join(', ')})` : typeof v === 'number' && prefix.startsWith('duration') ? `${v}ms` : v};`,
      );
  }
  return out;
};
const css = `/* GENERATED by tokens/scripts/build.mjs — do not edit. */\n:root {\n${cssVars(color, 0, '', []).join('\n')}\n${flat(space.space, 'space-').join('\n')}\n${flat(space.radius, 'radius-').join('\n')}\n${flat(space.layout, 'layout-').join('\n')}\n${flat(space.zIndex, 'z-').join('\n')}\n${flat(
  motion.duration,
  'duration-',
)
  .map(l => l.replace(/: (\d+);/, ': $1ms;'))
  .join('\n')}\n${flat(motion.entrance, 'entrance-')
  .map(l => l.replace(/: (\d+);/, ': $1ms;'))
  .join(
    '\n',
  )}\n${flat(motion.easing, 'ease-').join('\n')}\n${flat(motion.pressScale, 'press-').join('\n')}\n}\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n${cssVars(
  color,
  1,
  '',
  [],
)
  .map(l => '  ' + l)
  .join(
    '\n',
  )}\n  }\n}\n:root[data-theme="dark"] {\n${cssVars(color, 1, '', []).join('\n')}\n}\n`;

const prettierConfig =
  (await prettier.resolveConfig(join(root, 'package.json'))) ?? {};
const fmt = (content, parser) =>
  prettier.format(content, {...prettierConfig, parser});
const outputs = [
  [join(root, 'src', 'tokens', 'index.ts'), await fmt(ts, 'typescript')],
  [join(here, '..', 'dist', 'tokens.css'), await fmt(css, 'css')],
];
const check = process.argv.includes('--check');
let stale = 0;
for (const [file, content] of outputs) {
  const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (check) {
    if (current !== content) {
      console.error(`stale: ${file}`);
      stale++;
    }
  } else {
    mkdirSync(dirname(file), {recursive: true});
    writeFileSync(file, content);
    console.log(`wrote ${file}`);
  }
}
if (check) {
  if (stale) process.exit(1);
  console.log('tokens: outputs are current');
}
